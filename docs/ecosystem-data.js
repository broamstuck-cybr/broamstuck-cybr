export function bakeEcosystemGrid(rows, width, height, flipX = false) {
  const c = document.createElement("canvas");
  c.width = width;
  c.height = height;
  const ctx = c.getContext("2d");
  for (let y = 0; y < height; y++) {
    const row = rows[y] || "";
    for (let x = 0; x < width; x++) {
      const ch = row[x];
      if (!ch || ch === ".") continue;
      const hex = ECOSYSTEM_PALETTE[ch];
      if (!hex) continue;
      ctx.fillStyle = hex;
      const dx = flipX ? (width - 1 - x) : x;
      ctx.fillRect(dx, y, 1, 1);
    }
  }
  return c;
}

export function bakeCompanionSprites() {
  const bank = {};
  const speciesKeys = Object.keys(COMPANION_SPECIES_DEFS);
  for (let i = 0; i < speciesKeys.length; i++) {
    const sp = speciesKeys[i];
    const def = COMPANION_SPECIES_DEFS[sp];
    const right = {};
    const left = {};
    const frameKeys = Object.keys(def.frames);
    for (let k = 0; k < frameKeys.length; k++) {
      const fk = frameKeys[k];
      const grid = def.frames[fk];
      right[fk] = bakeEcosystemGrid(grid, def.width, def.height, false);
      left[fk] = bakeEcosystemGrid(grid, def.width, def.height, true);
    }
    bank[sp] = { width: def.width, height: def.height, right, left };
  }
  return bank;
}

export function bakePropSprites() {
  const bank = {};
  for (let i = 0; i < PROP_CATALOG.length; i++) {
    const p = PROP_CATALOG[i];
    bank[p.id] = {
      width: p.width,
      height: p.height,
      day: bakeEcosystemGrid(p.grid, p.width, p.height, false),
      night: p.nightGrid ? bakeEcosystemGrid(p.nightGrid, p.width, p.height, false) : null
    };
  }
  return bank;
}
